"""Model 10: AI Ensemble Regime-Switching Hidden Markov Model (HMM).

Mechanism:
- Financial asset returns are non-stationary and generated by switching latent market states.
- 3 Latent Structural States:
  * State 0: TRENDING_LOW_VOL (Bullish Expansion)
    - High positive drift, low annualized volatility (< 13%).
    - Action: Activate Trend/Momentum engines (Model 1 Cross-Sectional, Model 2 FII Flow). 100% equity exposure.
  * State 1: MEAN_REVERTING_SIDEWAYS (Chop / Consolidation)
    - Near-zero drift, medium volatility (13% - 19%).
    - Action: Activate Mean-Reversion & StatArb (Model 6 Residual Reversion, Model 4 Volume Profile). Tight range-bounds.
  * State 2: HIGH_VOL_PANIC (Liquidity Crunch / Crisis)
    - Negative drift, extreme volatility (> 19%).
    - Action: Move 70-80% to CASH / Liquid Bees. Barbell with asymmetric put hedges or VRP harvest (Model 8).
"""

from __future__ import annotations
import logging
import math
from typing import Any, Dict, List, Optional
import numpy as np

logger = logging.getLogger(__name__)


class InstitutionalHMMRegimeClassifier:
    """
    3-State Hidden Markov Model for market regime classification and strategy switching.
    Uses robust Gaussian emissions parameterized by empirical Indian equity benchmarks.
    """

    STATE_NAMES = {
        0: "TRENDING_LOW_VOL",
        1: "MEAN_REVERTING_SIDEWAYS",
        2: "HIGH_VOL_PANIC",
    }

    # Empirical State Emission Priors: (mean_daily_return, daily_volatility)
    # State 0: +0.08% daily (~20% ann), 0.65% daily vol (~10.3% ann)
    # State 1: +0.01% daily (~2.5% ann), 1.05% daily vol (~16.6% ann)
    # State 2: -0.22% daily (~ -55% ann), 1.85% daily vol (~29.3% ann)
    EMISSION_PARAMS = {
        0: {"mu": 0.0008, "sigma": 0.0065},
        1: {"mu": 0.0001, "sigma": 0.0105},
        2: {"mu": -0.0022, "sigma": 0.0185},
    }

    # Transition probability matrix (sticky regimes)
    TRANSITION_MATRIX = np.array([
        [0.92, 0.07, 0.01],  # State 0 tends to persist
        [0.08, 0.88, 0.04],  # State 1 can drift to bull or break into panic
        [0.05, 0.15, 0.80],  # State 2 mean-reverts slowly into State 1
    ])

    @classmethod
    def classify_regime(
        cls,
        recent_daily_returns: Optional[List[float]] = None,
        current_vix: float = 14.2,
    ) -> Dict[str, Any]:
        """
        Classifies the current market regime using log-likelihood emissions and transition dynamics.
        """
        if not recent_daily_returns or len(recent_daily_returns) < 5:
            # Deterministic baseline mapping using VIX
            if current_vix < 14.5:
                probs = [0.75, 0.20, 0.05]
            elif current_vix < 19.0:
                probs = [0.15, 0.70, 0.15]
            else:
                probs = [0.05, 0.20, 0.75]
        else:
            returns = np.array(recent_daily_returns[-20:], dtype=float)
            r_mean = float(np.mean(returns))
            r_std = float(np.std(returns)) if float(np.std(returns)) > 1e-6 else 0.01

            # Compute Gaussian likelihood for each state
            likelihoods = []
            for s in range(3):
                mu = cls.EMISSION_PARAMS[s]["mu"]
                sigma = cls.EMISSION_PARAMS[s]["sigma"]
                # Gaussian log-pdf sum across recent returns
                diff = returns - mu
                log_p = -0.5 * np.sum((diff / sigma) ** 2) - len(returns) * np.log(sigma * math.sqrt(2 * math.pi))
                likelihoods.append(log_p)

            # Softmax normalization for numerical stability
            max_log = max(likelihoods)
            exp_likes = [math.exp(lp - max_log) for lp in likelihoods]
            total_like = sum(exp_likes)
            raw_probs = [round(el / total_like, 4) for el in exp_likes]

            # Adjust probabilities with VIX prior
            if current_vix >= 20.0:
                raw_probs[2] = max(raw_probs[2], 0.60)
            elif current_vix <= 13.0:
                raw_probs[0] = max(raw_probs[0], 0.65)
            
            # Re-normalize
            s_sum = sum(raw_probs)
            probs = [round(p / s_sum, 4) for p in raw_probs]

        current_state_idx = int(np.argmax(probs))
        regime_name = cls.STATE_NAMES[current_state_idx]

        if current_state_idx == 0:
            active_strategies = [
                "Model 1: Cross-Sectional Momentum (Top Decile Longs)",
                "Model 2: FII OI Flow Trend Riding",
                "Model 5: Crypto-Equity Beta Expansion",
            ]
            recommended_equity_exposure = 1.0  # 100%
            risk_stance = "AGGRESSIVE_TREND_FOLLOWING"
            guidance = "Market is in State 0 (Trending Low Vol). Maximum alpha capture via cross-sectional momentum."
        elif current_state_idx == 1:
            active_strategies = [
                "Model 6: BankNifty StatArb Residual Reversion",
                "Model 4: Volume Profile & POC Value Area Bounces",
                "Model 9: BSE Smallcap Spread Capture",
            ]
            recommended_equity_exposure = 0.60  # 60%
            risk_stance = "MEAN_REVERSION_NEUTRAL"
            guidance = "Market is in State 1 (Sideways Mean-Reverting). Trade fading boundaries, pairs arbitrage, and order flow."
        else:
            active_strategies = [
                "Model 8: Volatility Risk Premium (VRP) Harvest (10Δ Strangles)",
                "Model 7: Event-Driven Macro Positioning",
                "Antifragile 80/20 Barbell (Liquid Bees + Tail Risk Puts)",
            ]
            recommended_equity_exposure = 0.20  # 20%
            risk_stance = "CAPITAL_PRESERVATION_PANIC"
            guidance = "Market is in State 2 (High Volatility Crisis). Stand down directional trend; preserve capital in cash/barbell."

        return {
            "model": "Model 10: AI Ensemble Regime-Switching HMM",
            "current_state_index": current_state_idx,
            "regime_name": regime_name,
            "state_probabilities": {
                "P(Trending_Low_Vol)": probs[0],
                "P(Mean_Reverting_Sideways)": probs[1],
                "P(High_Vol_Panic)": probs[2],
            },
            "recommended_equity_exposure_pct": round(recommended_equity_exposure * 100, 1),
            "risk_stance": risk_stance,
            "active_strategies": active_strategies,
            "guidance": guidance,
        }
